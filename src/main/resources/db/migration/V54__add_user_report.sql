-- 사용자 신고 테이블. 문제 신고(report)는 problem_id가 필수라 사용자 대상 신고를 따로 둔다
-- reported_nickname은 신고 시점 닉네임 스냅샷이다. 대상이 닉네임을 바꿔도 무엇이 신고됐는지 남는다
CREATE TABLE user_report
(
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY,
    reporter_id       BIGINT       NOT NULL,
    target_user_id    BIGINT       NOT NULL,
    report_type       VARCHAR(255) NOT NULL CHECK (report_type IN ('INAPPROPRIATE_NICKNAME', 'OTHER')),
    reported_nickname VARCHAR(255) NOT NULL,
    content           TEXT,
    is_resolved       BOOLEAN      NOT NULL,
    submitted_at      TIMESTAMP(6) NOT NULL,
    PRIMARY KEY (id)
);

-- 같은 신고자가 같은 대상에 처리되지 않은 신고를 두 개 이상 갖지 못하게 한다(동시 요청 방어)
CREATE UNIQUE INDEX IF NOT EXISTS ux_user_report_unresolved_pair
    ON user_report (reporter_id, target_user_id)
    WHERE is_resolved = false;

-- 닉네임 초기화 때 대상에게 걸린 처리되지 않은 신고를 찾는다
CREATE INDEX IF NOT EXISTS ix_user_report_target_unresolved
    ON user_report (target_user_id)
    WHERE is_resolved = false;
