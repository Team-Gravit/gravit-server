-- Apple 로그인 사용자의 Apple refresh_token. 탈퇴 시 Apple 연결 해제에 쓰며, AES-GCM 암호문으로 저장한다
-- user_id UNIQUE 제약이 사용자별 조회 인덱스를 겸한다
CREATE TABLE apple_credential (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id       BIGINT NOT NULL,
    refresh_token TEXT   NOT NULL,
    created_at    TIMESTAMP(6),
    updated_at    TIMESTAMP(6),
    CONSTRAINT uq_apple_credential_user_id UNIQUE (user_id),
    CONSTRAINT fk_apple_credential_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
);
