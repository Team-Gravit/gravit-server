```python
def topological_sort(graph, n):
    indegree = [0] * (n + 1)
    for i in range(1, n + 1):
        for node in graph[i]:
            indegree[node] += 1
    queue = deque(i for i in range(1, n + 1) if indegree[i] == 0)
    result = []
    while queue:
        now = queue.popleft()
        result.append(now)
        for nxt in graph[now]:
            indegree[nxt] -= 1
            if indegree[nxt] == 0:
                queue.append(nxt)
    if len(result) != n:
        return []
    return result

